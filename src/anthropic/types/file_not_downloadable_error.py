from typing_extensions import Literal

from .._exceptions import BadRequestError
from .file_not_downloadable_error_details import FileNotDownloadableErrorDetails

__all__ = ["FileNotDownloadableError"]


class FileNotDownloadableError(BadRequestError):
    """The file has `downloadable: false`.

    Only files generated by a tool, such as the code execution tool, can be downloaded.
    """

    error_code: Literal["file_not_downloadable"]  # pyright: ignore[reportIncompatibleVariableOverride]
    details: FileNotDownloadableErrorDetails  # pyright: ignore[reportIncompatibleVariableOverride]
